//! Finds the shipped shader plugins: every `src/fxlib/builtin/*.sksl` becomes one entry of `BUILTIN_PLUGINS`, so adding
//! a plugin is adding a file. The generated table is `(file stem, source)`, sorted by name.

use std::{env, fs, path::PathBuf};

const PLUGIN_DIR: &str = "src/fxlib/builtin";

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR")).join(PLUGIN_DIR);
    println!("cargo:rerun-if-changed={PLUGIN_DIR}");
    let mut files: Vec<PathBuf> = fs::read_dir(&dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())).map(|e| e.expect("a directory entry").path()).filter(|p| p.extension().is_some_and(|x| x == "sksl")).collect();
    files.sort();
    let mut table = String::from("/// Every shipped plugin as `(file stem, source)`, generated by build.rs from the plugin folder.\npub const BUILTIN_PLUGINS: &[(&str, &str)] = &[\n");
    for f in &files {
        let stem = f.file_stem().and_then(|s| s.to_str()).expect("plugin file names are UTF-8");
        table.push_str(&format!("    ({stem:?}, include_str!({:?})),\n", f.display().to_string()));
    }
    table.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("builtin_plugins.rs");
    fs::write(&out, table).unwrap_or_else(|e| panic!("writing {}: {e}", out.display()));
}
