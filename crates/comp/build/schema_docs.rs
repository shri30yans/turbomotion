//! Reads the schema's own source (`src/schema/*.rs`) and writes a table of every deserialisable struct and enum: field
//! names as serde reads them, their Rust types, doc comments and whether a key is required. `comp catalogue layer <name>`
//! prints from this table, so the reference is the parser's own declaration and cannot drift from it.

use std::{fmt::Write as _, fs, path::Path};

use syn::{punctuated::Punctuated, Attribute, Expr, Fields, GenericArgument, Item, Lit, Meta, PathArguments, Token, Type};

/// The schema files scanned, relative to the crate.
const SCHEMA_DIR: &str = "src/schema";

pub fn generate(manifest: &Path) -> String {
    let dir = manifest.join(SCHEMA_DIR);
    let mut files: Vec<_> = fs::read_dir(&dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())).map(|e| e.expect("a directory entry").path()).filter(|p| p.extension().is_some_and(|x| x == "rs")).collect();
    files.sort();
    let (mut structs, mut enums) = (String::new(), String::new());
    for f in files {
        let text = fs::read_to_string(&f).unwrap_or_else(|e| panic!("reading {}: {e}", f.display()));
        let file = syn::parse_file(&text).unwrap_or_else(|e| panic!("parsing {}: {e}", f.display()));
        for item in file.items {
            match item {
                Item::Struct(s) if derives_deserialize(&s.attrs) => {
                    let container_default = serde_flag(&s.attrs, "default");
                    let Fields::Named(named) = &s.fields else { continue };
                    let mut rows = String::new();
                    for field in &named.named {
                        let ident = field.ident.as_ref().expect("named").to_string();
                        let key = serde_value(&field.attrs, "rename").unwrap_or(ident);
                        let is_option = matches!(render(&field.ty).as_str(), t if t.starts_with("Option<"));
                        let required = !(container_default || serde_flag(&field.attrs, "default") || is_option);
                        let _ = writeln!(rows, "        SchemaField {{ key: {key:?}, ty: {:?}, doc: {:?}, required: {required} }},", render(&field.ty), docs(&field.attrs));
                    }
                    let _ = writeln!(structs, "    SchemaStruct {{ name: {:?}, doc: {:?}, fields: &[\n{rows}    ] }},", s.ident.to_string(), docs(&s.attrs));
                }
                Item::Enum(e) if derives_deserialize(&e.attrs) => {
                    let snake = serde_value(&e.attrs, "rename_all").as_deref() == Some("snake_case");
                    let mut rows = String::new();
                    for v in &e.variants {
                        let ident = v.ident.to_string();
                        let name = serde_value(&v.attrs, "rename").unwrap_or_else(|| if snake { snake_case(&ident) } else { ident });
                        let _ = writeln!(rows, "        SchemaVariant {{ name: {name:?}, doc: {:?} }},", docs(&v.attrs));
                    }
                    let _ = writeln!(enums, "    SchemaEnum {{ name: {:?}, doc: {:?}, variants: &[\n{rows}    ] }},", e.ident.to_string(), docs(&e.attrs));
                }
                _ => {}
            }
        }
    }
    format!("/// Generated by build.rs from `src/schema/*.rs`.\npub const SCHEMA_STRUCTS: &[SchemaStruct] = &[\n{structs}];\n\n/// Generated by build.rs from `src/schema/*.rs`.\npub const SCHEMA_ENUMS: &[SchemaEnum] = &[\n{enums}];\n")
}

fn derives_deserialize(attrs: &[Attribute]) -> bool {
    attrs.iter().filter(|a| a.path().is_ident("derive")).any(|a| a.parse_args_with(Punctuated::<syn::Path, Token![,]>::parse_terminated).is_ok_and(|paths| paths.iter().any(|p| p.is_ident("Deserialize"))))
}

/// Every `#[serde(...)]` meta in `attrs`.
fn serde_metas(attrs: &[Attribute]) -> Vec<Meta> {
    attrs.iter().filter(|a| a.path().is_ident("serde")).flat_map(|a| a.parse_args_with(Punctuated::<Meta, Token![,]>::parse_terminated).map(|p| p.into_iter().collect::<Vec<_>>()).unwrap_or_default()).collect()
}

/// Is `#[serde(name)]` or `#[serde(name = "...")]` present?
fn serde_flag(attrs: &[Attribute], name: &str) -> bool {
    serde_metas(attrs).iter().any(|m| m.path().is_ident(name))
}

/// The string of `#[serde(name = "value")]`.
fn serde_value(attrs: &[Attribute], name: &str) -> Option<String> {
    serde_metas(attrs).into_iter().find_map(|m| match m {
        Meta::NameValue(nv) if nv.path.is_ident(name) => match nv.value {
            Expr::Lit(l) => match l.lit {
                Lit::Str(s) => Some(s.value()),
                _ => None,
            },
            _ => None,
        },
        _ => None,
    })
}

/// The `///` lines, joined with spaces.
fn docs(attrs: &[Attribute]) -> String {
    let lines: Vec<String> = attrs
        .iter()
        .filter(|a| a.path().is_ident("doc"))
        .filter_map(|a| match &a.meta {
            Meta::NameValue(nv) => match &nv.value {
                Expr::Lit(l) => match &l.lit {
                    Lit::Str(s) => Some(s.value().trim().to_string()),
                    _ => None,
                },
                _ => None,
            },
            _ => None,
        })
        .collect();
    lines.join(" ").trim().to_string()
}

fn snake_case(ident: &str) -> String {
    let mut out = String::new();
    for (i, c) in ident.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// A type as the author of the schema wrote it: `Option<P>`, `[f64; 2]`, `Vec<Mask>`.
fn render(ty: &Type) -> String {
    match ty {
        Type::Path(p) => {
            let seg = p.path.segments.last().expect("a path has a segment");
            match &seg.arguments {
                PathArguments::AngleBracketed(args) => {
                    let inner: Vec<String> = args.args.iter().filter_map(|a| if let GenericArgument::Type(t) = a { Some(render(t)) } else { None }).collect();
                    format!("{}<{}>", seg.ident, inner.join(", "))
                }
                _ => seg.ident.to_string(),
            }
        }
        Type::Array(a) => {
            let len = match &a.len {
                Expr::Lit(l) => match &l.lit {
                    Lit::Int(i) => i.base10_digits().to_string(),
                    _ => "N".into(),
                },
                _ => "N".into(),
            };
            format!("[{}; {len}]", render(&a.elem))
        }
        Type::Tuple(t) => format!("({})", t.elems.iter().map(render).collect::<Vec<_>>().join(", ")),
        _ => "?".into(),
    }
}
