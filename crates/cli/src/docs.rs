//! `turbomotion docs`: the reference pages, written from the code that defines them. The layer kinds, transitions,
//! effects and presets come from the engine's catalogue; the SDK pages come from the doc comments and signatures in the
//! SDK sources. Nothing here is typed by hand, so a page can only be stale until the next `docs --write`, and the test
//! in `tests/docs.rs` (and CI) fails until then.

use std::{fmt::Write as _, fs, path::Path};

use anyhow::{bail, Context, Result};
use serde_json::Value;

/// Every generated page as `(file name, markdown)`.
pub fn pages() -> Vec<(String, String)> {
    let c = turbomotion_comp::catalogue::all();
    let mut out = vec![
        ("layers.md".to_string(), layers(&c)),
        ("timeline.md".to_string(), timeline(&c)),
        ("effects.md".to_string(), effects(&c)),
        ("text-and-motion.md".to_string(), motion(&c)),
        ("sdk.md".to_string(), sdk()),
    ];
    out.push(("README.md".to_string(), index(&out)));
    out
}

const BANNER: &str = "<!-- Generated by `turbomotion docs --write`. Do not edit by hand: change the code or its doc comments. -->\n\n";

/// Write the pages into `dir`, or with `check` fail naming each page that differs from what is on disk.
pub fn run(dir: &Path, check: bool) -> Result<()> {
    let pages = pages();
    if check {
        let stale: Vec<_> = pages.iter().filter(|(n, text)| fs::read_to_string(dir.join(n)).ok().as_deref() != Some(text)).map(|(n, _)| n.as_str()).collect();
        if !stale.is_empty() {
            bail!("generated docs are out of date ({}): run `turbomotion docs --write`", stale.join(", "));
        }
        println!("docs are current ({} pages in {})", pages.len(), dir.display());
        return Ok(());
    }
    fs::create_dir_all(dir)?;
    for (name, text) in &pages {
        fs::write(dir.join(name), text).with_context(|| format!("writing {name}"))?;
    }
    println!("wrote {} pages to {}", pages.len(), dir.display());
    Ok(())
}


fn str_of<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

fn json_block(out: &mut String, v: &Value) {
    let _ = writeln!(out, "```json\n{}\n```\n", serde_json::to_string_pretty(v).unwrap_or_default());
}

fn page(title: &str, intro: &str) -> String {
    format!("{BANNER}# {title}\n\n{intro}\n\n")
}

fn index(pages: &[(String, String)]) -> String {
    let mut s = page("Reference", "Every page here is generated from the code. Refresh with `turbomotion docs --write`; `turbomotion docs --check` (run by the tests and CI) fails when one is stale.");
    for (name, text) in pages {
        let title = text.lines().find_map(|l| l.strip_prefix("# ")).unwrap_or(name);
        let _ = writeln!(s, "* [{title}]({name})");
    }
    s
}

fn layers(c: &Value) -> String {
    let mut s = page("Layer kinds", "What a composition's `layers` can hold. `turbomotion comp catalogue` prints the same data as JSON.");
    for l in c["layers"].as_array().into_iter().flatten() {
        let _ = writeln!(s, "## `{}`\n\n{}\n", str_of(l, "name"), str_of(l, "summary"));
        json_block(&mut s, &l["example"]);
    }
    let x = &c["extrude"];
    let _ = writeln!(s, "## `extrude`\n\n{}\n", str_of(x, "summary"));
    json_block(&mut s, &x["example"]);
    s
}

fn timeline(c: &Value) -> String {
    let t = &c["timeline"];
    let mut s = page("Timeline", str_of(t, "summary"));
    let _ = writeln!(s, "Shot fields: {}\n", str_of(t, "shot_fields"));
    json_block(&mut s, &t["example"]);
    for (heading, key, field) in [("Transitions", "transitions", "type"), ("Shot moves", "moves", "move"), ("Camera moves", "camera_moves", "move")] {
        let _ = writeln!(s, "## {heading}\n\n| name | what it does |\n| --- | --- |");
        for e in t[key].as_array().into_iter().flatten() {
            let _ = writeln!(s, "| `{}` | {} |", str_of(e, field), str_of(e, "summary").replace('|', "\\|"));
        }
        s.push('\n');
    }
    s
}

fn effects(c: &Value) -> String {
    let mut s = page("Effects", &format!("Every effect and generator, from its descriptor: platform effects first, then the shipped shader plugins. {}", str_of(c, "make_a_new_effect")));
    let composite = &c["effect_composite"];
    let _ = writeln!(s, "## Composite options (every effect)\n\n{}\n", str_of(composite, "summary"));
    for (key, what) in composite["keys"].as_object().into_iter().flatten() {
        let _ = writeln!(s, "* `{key}`: {}", what.as_str().unwrap_or_default());
    }
    s.push('\n');
    json_block(&mut s, &composite["example"]);
    for e in c["effects"].as_array().into_iter().flatten() {
        let (what, origin) = (str_of(e, "kind"), str_of(e, "origin"));
        let _ = writeln!(s, "## `{}`\n\n{} ({what}, {})\n", str_of(e, "name"), str_of(e, "summary"), if origin == "rust" { "platform" } else { "shader plugin" });
        param_table(&mut s, &e["params"]);
        for i in e["inputs"].as_array().into_iter().flatten() {
            let how = if str_of(i, "kind") == "history" { format!("its own output {} frame(s) back, recursion {} deep", i["frames"], i["depth"]) } else { "the picture of another layer, named by id".to_string() };
            let _ = writeln!(s, "* input `{}`: {how} -- {}", str_of(i, "name"), str_of(i, "doc"));
        }
        let passes = e["passes"].as_array().map_or(0, Vec::len);
        if passes > 1 {
            let names: Vec<String> = e["passes"].as_array().into_iter().flatten().map(|p| format!("`{}` (x{})", str_of(p, "name"), p["scale"])).collect();
            let _ = writeln!(s, "* passes: {}", names.join(", "));
        }
        s.push('\n');
        json_block(&mut s, &e["example"]);
    }
    s
}

/// A choice's default is shown by name, an optional parameter's as `none`, a float's as the bare number; a vector or a
/// colour as written.
fn default_of(p: &Value) -> String {
    if p["optional"].as_bool() == Some(true) {
        return "none".to_string();
    }
    match (p["options"].as_array().filter(|o| !o.is_empty()), p["default"].as_array().map(Vec::as_slice)) {
        (Some(options), Some([at])) => at.as_f64().and_then(|at| options.get(at as usize)).and_then(Value::as_str).unwrap_or_default().to_string(),
        (None, Some([only])) => only.to_string(),
        _ => p["default"].to_string(),
    }
}

/// What values a parameter may take: its range (limited to it, either end open), or its options.
fn range_of(p: &Value) -> String {
    match (p["min"].as_f64(), p["max"].as_f64()) {
        (Some(lo), Some(hi)) => format!("{lo} to {hi}"),
        (Some(lo), None) => format!("{lo} or more"),
        (None, Some(hi)) => format!("{hi} or less"),
        (None, None) => p["options"].as_array().filter(|o| !o.is_empty()).map_or(String::new(), |o| o.iter().filter_map(Value::as_str).collect::<Vec<_>>().join(", ")),
    }
}

fn param_table(s: &mut String, params: &Value) {
    let Some(rows) = params.as_array().filter(|r| !r.is_empty()) else { return };
    let _ = writeln!(s, "| parameter | type | default | range | what it does |\n| --- | --- | --- | --- | --- |");
    for p in rows {
        let _ = writeln!(s, "| `{}` | {} | {} | {} | {} |", str_of(p, "name"), str_of(p, "ty"), default_of(p), range_of(p), str_of(p, "doc").replace('|', "\\|"));
    }
    s.push('\n');
}

fn motion(c: &Value) -> String {
    let mut s = page("Text, motion and expressions", "Text presets, enter and exit presets, eases, expressions and the sound kit.");
    let names = |v: &Value| v.as_array().into_iter().flatten().filter_map(Value::as_str).map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ");
    let _ = writeln!(s, "## Text presets\n\n{}\n", names(&c["text_presets"]));
    let _ = writeln!(s, "## Enter and exit presets\n\n| preset | what it does |\n| --- | --- |");
    for p in c["enter_exit_presets"].as_array().into_iter().flatten() {
        let _ = writeln!(s, "| `{}` | {} |", str_of(p, "preset"), str_of(p, "summary").replace('|', "\\|"));
    }
    let _ = writeln!(s, "\n## Eases\n\n{}\n\n## Time literals\n\n{}\n\n## Colour forms\n\n{}\n", names(&c["eases"]), names(&c["time_literals"]), names(&c["colour_forms"]));
    let _ = writeln!(s, "## Expressions\n");
    for (k, v) in c["expressions"].as_object().into_iter().flatten() {
        let _ = writeln!(s, "* **{k}**: {}", match v { Value::Array(_) => names(v), other => other.as_str().unwrap_or("").to_string() });
    }
    let _ = writeln!(s, "\n## Sound kit\n\n| cue | timbre |\n| --- | --- |");
    for q in c["sound_kit"]["cues"].as_array().into_iter().flatten() {
        let _ = writeln!(s, "| `{}` | {} |", str_of(q, "cue"), str_of(q, "timbre"));
    }
    s
}

/// A documented declaration found in an SDK source file.
struct Item {
    signature: String,
    doc: String,
}

/// The leading `//` comment block of a module, then each `export` preceded by a `/** */` comment.
fn read_module(src: &str) -> (String, Vec<Item>) {
    let head: Vec<_> = src.lines().take_while(|l| l.starts_with("//")).map(|l| l.trim_start_matches('/').trim()).collect();
    let (mut items, mut doc, mut open) = (vec![], String::new(), false);
    for line in src.lines() {
        let t = line.trim();
        if t.starts_with("/**") {
            open = !t.ends_with("*/");
            doc = t.trim_start_matches("/**").trim_end_matches("*/").trim().to_string();
        } else if open {
            open = !t.ends_with("*/");
            let piece = t.trim_end_matches("*/").trim_start_matches('*').trim();
            if !piece.is_empty() {
                if !doc.is_empty() { doc.push(' '); }
                doc.push_str(piece);
            }
        } else if line.starts_with("export ") && !line.starts_with("export {") && !line.starts_with("export *") && !line.starts_with("export type {") {
            if !doc.is_empty() {
                let line = line.split(" => ").next().unwrap_or(line);
                let signature = line.trim_end().trim_end_matches('{').trim_end().to_string();
                items.push(Item { signature, doc: std::mem::take(&mut doc) });
            }
        } else if !t.is_empty() {
            doc.clear();
        }
    }
    (head.join(" ").trim().to_string(), items)
}

fn sdk() -> String {
    let mut s = page("TypeScript SDK", "The functions a film imports from `\"turbomotion\"`, taken from the doc comments on the exports in `crates/script/sdk`. Only documented exports are listed.");
    let mut sources = turbomotion_script::sdk_sources().to_vec();
    sources.retain(|(name, _)| *name != "index");
    sources.sort_by_key(|(name, _)| *name);
    for (name, src) in sources {
        let (head, items) = read_module(src);
        if items.is_empty() { continue; }
        let _ = writeln!(s, "## `{name}`\n");
        if !head.is_empty() { let _ = writeln!(s, "{head}\n"); }
        for i in items {
            let _ = writeln!(s, "```ts\n{}\n```\n{}\n", i.signature, i.doc);
        }
    }
    s
}
