//! Embeds every `sdk/**/*.ts` file in the binary. The module table is generated from the folder, so a new SDK file
//! needs no registration and an SDK file can never be missing from the binary by omission.

use std::{env, fmt::Write as _, fs, path::{Path, PathBuf}};

fn modules(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir).expect("read sdk folder").map(|e| e.expect("sdk entry").path()).collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            modules(root, &path, out);
        } else if path.extension().is_some_and(|e| e == "ts") {
            let name = path.strip_prefix(root).unwrap().with_extension("");
            out.push((name.to_string_lossy().replace('\\', "/"), path));
        }
    }
}

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("sdk");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut found = Vec::new();
    modules(&root, &root, &mut found);
    let mut table = String::from("/// Generated by build.rs from `sdk/**/*.ts`.\npub const SDK: &[(&str, &str)] = &[\n");
    for (name, path) in &found {
        writeln!(table, "    ({name:?}, include_str!({:?})),", path.to_string_lossy()).unwrap();
    }
    table.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("sdk_modules.rs"), table).unwrap();
}
